def benchmark_model_latency(
    checkpoint_path: Path,
    repeat: int,
    warmup: int,
) -> dict:
    import torch

    from models import build_model

    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    input_size = int(checkpoint["input_size"])
    hidden_size = int(checkpoint.get("hidden_size", 64))
    num_layers = int(checkpoint.get("num_layers", 2))
    dropout = float(checkpoint.get("dropout", 0.1))
    model_name = checkpoint.get("model_name", "mtpnet")
    sequence_length = int(checkpoint.get("sequence_length", 60))

    model = build_model(
        name=model_name,
        input_size=input_size,
        hidden_size=hidden_size,
        num_layers=num_layers,
        dropout=dropout,
    )
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    x = torch.randn(1, sequence_length, input_size)

    with torch.no_grad():
        for _ in range(warmup):
            model(x)
        durations = []
        for _ in range(repeat):
            start = time.perf_counter()
            model(x)
            durations.append((time.perf_counter() - start) * 1000.0)

    values = np.array(durations, dtype=np.float64)
    return {
        "checkpoint": str(checkpoint_path),
        "model": model_name,
        "sequence_length": sequence_length,
        "input_size": input_size,
        "mean_ms": float(np.mean(values)),
        "p50_ms": float(np.percentile(values, 50)),
        "p95_ms": float(np.percentile(values, 95)),
        "fps_equivalent": float(1000.0 / max(np.mean(values), 1e-9)),
        "repeat": repeat,
        "warmup": warmup,
    }


def write_latency_table(experiment_dir: Path, repeat: int, warmup: int) -> None:
    rows = []
    for metadata_path in sorted((experiment_dir / "models").glob("*/training_metadata.json")):
        metadata = read_json(metadata_path)
        checkpoint_path = Path(metadata.get("model_path", ""))
        if not checkpoint_path.exists():
            checkpoint_path = metadata_path.parent / "best_model.pt"
        if checkpoint_path.exists():
            rows.append(benchmark_model_latency(checkpoint_path, repeat, warmup))
    write_csv(
        experiment_dir / "tables" / "table_4_7_temporal_model_latency.csv",
        rows,
        [
            "model",
            "sequence_length",
            "input_size",
            "mean_ms",
            "p50_ms",
            "p95_ms",
            "fps_equivalent",
            "repeat",
            "warmup",
            "checkpoint",
        ],
    )


def main() -> None:
    args = parse_arguments()
    dataset_dir = resolve_path(args.dataset_dir)
    if not dataset_dir.exists():
        raise FileNotFoundError(f"Dataset directory not found: {dataset_dir}")

    experiment_dir = create_experiment_dir(resolve_path(args.output_root))
    tables_dir = experiment_dir / "tables"
    write_json(
        experiment_dir / "experiment_manifest.json",
        {
            "created_at": datetime.now().isoformat(timespec="seconds"),
            "dataset_dir": str(dataset_dir),
            "args": vars(args),
        },
    )

    write_dataset_summary(dataset_dir, tables_dir)
    write_model_settings_table(tables_dir, args)
    write_template_tables(tables_dir)

    dataset_variants = {"full": dataset_dir}
    if not args.skip_ablations:
        for variant in ["no_pairwise_risk", "no_risk_type", "traffic_state_only"]:
            dataset_variants[variant] = create_feature_ablation_dataset(
                source_dataset_dir=dataset_dir,
                target_dataset_dir=experiment_dir / "ablated_datasets" / variant,
                variant=variant,
            )

    if not args.skip_training:
        for model_name in args.models:
            run_training(
                dataset_dir=dataset_dir,
                model_name=model_name,
                output_dir=experiment_dir / "models" / model_name,
                args=args,
            )
        if not args.skip_ablations:
            for spec in ABLATION_EXPERIMENTS:
                run_training(
                    dataset_dir=dataset_variants[spec["dataset_variant"]],
                    model_name=spec["model"],
                    output_dir=experiment_dir / "models" / spec["name"],
                    args=args,
                )

    collect_comparison_tables(
        experiment_dir=experiment_dir,
        models=args.models,
        include_ablations=not args.skip_ablations,
    )

    if not args.skip_latency:
        write_latency_table(
            experiment_dir=experiment_dir,
            repeat=args.latency_repeat,
            warmup=args.latency_warmup,
        )

    print(f"Chapter 4 experiment outputs saved to: {experiment_dir}")
    print(f"Tables saved to: {tables_dir}")


if __name__ == "__main__":
    main()
