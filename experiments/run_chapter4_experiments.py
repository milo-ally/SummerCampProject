def resolve_path(path_text: str) -> Path:
    path = Path(path_text)
    if path.exists():
        return path
    project_path = PROJECT_ROOT / path
    return project_path if project_path.exists() else path


def create_experiment_dir(output_root: Path) -> Path:
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_dir = output_root / f"{timestamp}_chapter4"
    output_dir.mkdir(parents=True, exist_ok=False)
    (output_dir / "tables").mkdir()
    (output_dir / "models").mkdir()
    (output_dir / "ablated_datasets").mkdir()
    return output_dir


def read_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def write_json(path: Path, payload: dict) -> None:
    with path.open("w", encoding="utf-8") as file:
        json.dump(payload, file, ensure_ascii=False, indent=2)


def write_csv(path: Path, rows: list[dict], fieldnames: list[str] | None = None) -> None:
    if fieldnames is None:
        fieldnames = sorted({key for row in rows for key in row})
    with path.open("w", newline="", encoding="utf-8-sig") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def load_npz(dataset_dir: Path, split: str) -> tuple[np.ndarray, np.ndarray]:
    data = np.load(dataset_dir / f"{split}.npz")
    return data["X"].astype(np.float32), data["y"].astype(np.float32)


def write_dataset_summary(dataset_dir: Path, tables_dir: Path) -> None:
    metadata = read_json(dataset_dir / "dataset_metadata.json")
    rows = []
    for split in ["train", "val", "test"]:
        X, y = load_npz(dataset_dir, split)
        rows.append(
            {
                "split": split,
                "samples": int(len(y)),
                "positive_samples": int(y.sum()),
                "negative_samples": int(len(y) - y.sum()),
                "positive_ratio": f"{float(y.mean()) if len(y) else 0.0:.6f}",
                "sequence_length": int(X.shape[1]) if X.ndim == 3 else "",
                "feature_dim": int(X.shape[2]) if X.ndim == 3 else "",
            }
        )
    rows.append(
        {
            "split": "total",
            "samples": int(metadata.get("samples", 0)),
            "positive_samples": int(metadata.get("positive_samples", 0)),
            "negative_samples": int(metadata.get("negative_samples", 0)),
            "positive_ratio": f"{metadata.get('positive_samples', 0) / max(metadata.get('samples', 1), 1):.6f}",
            "sequence_length": int(metadata.get("window_size", 0)),
            "feature_dim": len(metadata.get("feature_columns", [])),
        }
    )
    write_csv(
        tables_dir / "table_4_1_dataset_summary.csv",
        rows,
        [
            "split",
            "samples",
            "positive_samples",
            "negative_samples",
            "positive_ratio",
            "sequence_length",
            "feature_dim",
        ],
    )


def selected_feature_indices(feature_columns: list[str], variant: str) -> list[int]:
    if variant == "full":
        return list(range(len(feature_columns)))
    if variant == "no_pairwise_risk":
        return [
            index
            for index, column in enumerate(feature_columns)
            if "P_ij" not in column and "pair" not in column.lower()
        ]
    if variant == "no_risk_type":
        return [
            index
            for index, column in enumerate(feature_columns)
            if not column.startswith("risk_type_")
        ]
    if variant == "traffic_state_only":
        keep_keywords = ["rho", "N(t)", "vehicle_count"]
        keep_exact = {"risk_type_long", "risk_type_lat"}
        indices = []
        for index, column in enumerate(feature_columns):
            if column in keep_exact:
                continue
            if any(keyword in column for keyword in keep_keywords):
                indices.append(index)
        if not indices:
            indices = [index for index in range(len(feature_columns)) if index in (1, 2, 3)]
        return indices
    raise ValueError(f"Unknown feature ablation variant: {variant}")


def create_feature_ablation_dataset(
    source_dataset_dir: Path,
    target_dataset_dir: Path,
    variant: str,
) -> Path:
    metadata = read_json(source_dataset_dir / "dataset_metadata.json")
    feature_columns = list(metadata.get("feature_columns", []))
    indices = selected_feature_indices(feature_columns, variant)
    target_dataset_dir.mkdir(parents=True, exist_ok=False)

    for split in ["train", "val", "test"]:
        X, y = load_npz(source_dataset_dir, split)
        np.savez_compressed(target_dataset_dir / f"{split}.npz", X=X[:, :, indices], y=y)

    selected_columns = [feature_columns[index] for index in indices]
    metadata["source_dataset_dir"] = str(source_dataset_dir)
    metadata["ablation_variant"] = variant
    metadata["feature_columns"] = selected_columns
    metadata["feature_mean"] = [
        metadata.get("feature_mean", [])[index]
        for index in indices
        if index < len(metadata.get("feature_mean", []))
    ]
    metadata["feature_std"] = [
        metadata.get("feature_std", [])[index]
        for index in indices
        if index < len(metadata.get("feature_std", []))
    ]
    write_json(target_dataset_dir / "dataset_metadata.json", metadata)
    write_json(target_dataset_dir / "feature_columns.json", selected_columns)
    source_index = source_dataset_dir / "sequence_index.csv"
    if source_index.exists():
        shutil.copy2(source_index, target_dataset_dir / "sequence_index.csv")
    return target_dataset_dir


