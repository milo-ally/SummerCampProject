def collect_model_metrics(model_output_dir: Path, label: str) -> dict | None:
    metadata_path = model_output_dir / "training_metadata.json"
    if not metadata_path.exists():
        return None
    metadata = read_json(metadata_path)
    metrics = metadata.get("test_metrics", {})
    return {
        "experiment": label,
        "model": metadata.get("model", label),
        "accuracy": metrics.get("accuracy", ""),
        "precision": metrics.get("precision", ""),
        "recall": metrics.get("recall", ""),
        "f1_score": metrics.get("f1", ""),
        "roc_auc": metrics.get("auc", ""),
        "loss": metrics.get("loss", ""),
        "best_epoch": metadata.get("best_epoch", ""),
        "best_val_loss": metadata.get("best_val_loss", ""),
        "model_path": metadata.get("model_path", ""),
    }


